package com.animo.app.data.update

import android.content.Context
import androidx.datastore.preferences.core.edit
import androidx.datastore.preferences.core.stringPreferencesKey
import com.animo.app.AppLog
import com.animo.app.BuildConfig
import com.animo.app.ui.changelog.Release
import com.animo.app.ui.theme.animoUiPreferences
import java.io.IOException
import java.util.concurrent.TimeUnit
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.distinctUntilChanged
import kotlinx.coroutines.flow.map
import kotlinx.coroutines.withContext
import kotlinx.serialization.json.Json
import okhttp3.OkHttpClient
import okhttp3.Request

/**
 * Version tracking for the installed build.
 *
 * The app polls one small JSON document published next to the landing page. It is served by GitHub
 * Pages (CDN, no auth, no API quota) and regenerated by a workflow every time a release is
 * published, so "is there a newer build?" never depends on shipping code first.
 *
 * Failure is silent by design: a device with no network, a blocked CDN or a malformed feed must
 * never block start-up or show an error — an update check is the least important thing the app does.
 */
class UpdateCenter private constructor(context: Context) {

    private val appContext = context.applicationContext

    private val json = Json {
        ignoreUnknownKeys = true
        isLenient = true
        coerceInputValues = true
    }

    /**
     * Its own client on purpose: [com.animo.app.di.ServiceLocator]'s client is wired for provider
     * hosts (budgets, header replay, WebView fallback) and none of that belongs on a static file.
     */
    private val client = OkHttpClient.Builder()
        .connectTimeout(8, TimeUnit.SECONDS)
        .readTimeout(8, TimeUnit.SECONDS)
        .callTimeout(12, TimeUnit.SECONDS)
        .build()

    @Volatile
    private var cached: UpdateFeed? = null

    @Volatile
    private var cachedAt: Long = 0L

    /** The version the user has waved away; it never prompts again until a newer one exists. */
    val dismissedVersion: Flow<String?> = appContext.animoUiPreferences.data
        .map { prefs -> prefs[DismissedVersionKey] }
        .distinctUntilChanged()

    /** Version code of the running build — the only thing the comparison uses. */
    val currentVersionCode: Int get() = BuildConfig.VERSION_CODE

    /** Version name of the running build, for copy that says "you are on 1.9.0". */
    val currentVersionName: String get() = BuildConfig.VERSION_NAME

    suspend fun feed(force: Boolean = false): UpdateFeed? {
        val fresh = cached
        val age = System.currentTimeMillis() - cachedAt
        if (!force && fresh != null && age < CACHE_TTL_MS) return fresh
        return fetch() ?: fresh
    }

    private suspend fun fetch(): UpdateFeed? = withContext(Dispatchers.IO) {
        try {
            val request = Request.Builder()
                .url(FEED_URL)
                .header("Accept", "application/json")
                .build()
            client.newCall(request).execute().use { response ->
                if (!response.isSuccessful) {
                    AppLog.w("update feed: HTTP ${response.code}")
                    return@withContext null
                }
                val body = response.body?.string().orEmpty()
                if (body.isBlank()) return@withContext null
                val parsed = json.decodeFromString<UpdateFeed>(body)
                if (parsed.latest == null || parsed.latest.versionCode <= 0) {
                    AppLog.w("update feed: no usable latest block")
                    return@withContext null
                }
                cached = parsed
                cachedAt = System.currentTimeMillis()
                parsed
            }
        } catch (e: IOException) {
            AppLog.w("update feed unreachable: ${e.message}")
            null
        } catch (e: Exception) {
            // A malformed feed is a publishing bug, not a user-facing failure.
            AppLog.w("update feed unreadable: ${e.message}")
            null
        }
    }

    /**
     * Releases newer than the installed build, newest first. Empty when the build is current, when
     * the feed is unavailable, or when the feed only describes what this build already ships.
     */
    fun newerReleases(feed: UpdateFeed?): List<Release> = feed
        ?.releases
        .orEmpty()
        .filter { it.versionCode > currentVersionCode }
        .sortedByDescending { it.versionCode }
        .map { it.toRelease() }

    /** True when [feed] advertises a build the user has not seen or dismissed yet. */
    fun isUpdateAvailable(feed: UpdateFeed?, dismissed: String?): Boolean {
        val latest = feed?.latest ?: return false
        if (latest.versionCode <= currentVersionCode) return false
        return dismissed != latest.version
    }

    /** Last successful fetch, for screens that want the feed without awaiting one. */
    fun cachedFeed(): UpdateFeed? = cached

    suspend fun dismiss(version: String) {
        appContext.animoUiPreferences.edit { prefs -> prefs[DismissedVersionKey] = version }
    }

    companion object {
        /** Public, CDN-served, tiny. Kept in sync with docs/update.json. */
        const val FEED_URL = "https://1hp2die.github.io/Dr-Animo/update.json"

        /** Six hours: long enough to stay off the network, short enough to catch a same-day release. */
        private const val CACHE_TTL_MS = 6L * 60 * 60 * 1000

        private val DismissedVersionKey = stringPreferencesKey("update_dismissed_version")

        @Volatile
        private var instance: UpdateCenter? = null

        /** One per process: the fetch, the cache and the dismissal state are shared by every screen. */
        fun get(context: Context): UpdateCenter =
            instance ?: synchronized(this) {
                instance ?: UpdateCenter(context).also { instance = it }
            }
    }
}

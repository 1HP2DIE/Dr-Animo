// ============================================================================
// Endpoint vault
//
// `secrets/providers.properties` (git-ignored) is the only place a real host exists. At
// build time it is encrypted with AES-256-GCM into `assets/pv.bin`, and a per-build key is
// emitted as masked, split longs into generated Kotlin. The runtime decrypts once and caches
// in memory: a few microseconds at startup, nothing per request.
// ============================================================================

val vaultBuildDir = layout.buildDirectory.dir("generated/vault")

val generateProviderVault = tasks.register("generateProviderVault") {
    val secretsFile = rootProject.file("secrets/providers.properties")
    val keyFile = rootProject.file("secrets/vault.key")
    val outDir = vaultBuildDir.get().asFile

    inputs.files(secretsFile, keyFile).withPropertyName("vaultInputs").optional()
    outputs.dir(outDir)

    doLast {
        val props = Properties()
        if (secretsFile.isFile) secretsFile.inputStream().use { props.load(it) }

        val random = SecureRandom()
        val key = if (keyFile.isFile && keyFile.readText().trim().length == 64) {
            keyFile.readText().trim().chunked(2).map { it.toInt(16).toByte() }.toByteArray()
        } else {
            ByteArray(32).also { random.nextBytes(it) }.also { created ->
                keyFile.parentFile?.mkdirs()
                keyFile.writeText(created.joinToString("") { "%02x".format(it) })
            }
        }

        // ---- plaintext: count + (id, value)*
        val buffer = ByteArrayOutputStream()
        val data = DataOutputStream(buffer)
        val names = props.stringPropertyNames().sorted()
        data.writeInt(names.size)
        names.forEach { name ->
            val id = name.toByteArray(Charsets.UTF_8)
            val value = (props.getProperty(name) ?: "").toByteArray(Charsets.UTF_8)
            data.writeInt(id.size); data.write(id)
            data.writeInt(value.size); data.write(value)
        }
        data.flush()

        val iv = ByteArray(12).also { random.nextBytes(it) }
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.ENCRYPT_MODE, SecretKeySpec(key, "AES"), GCMParameterSpec(128, iv))
        val ciphertext = cipher.doFinal(buffer.toByteArray())

        val asset = ByteArrayOutputStream()
        asset.write("PVA1".toByteArray(Charsets.UTF_8))
        asset.write(iv)
        asset.write(ciphertext)

        val assetsDir = File(outDir, "assets").apply { mkdirs() }
        File(assetsDir, "pv.bin").writeBytes(asset.toByteArray())

        // ---- key material: four 64-bit chunks, each stored XOR-masked with its own constant
        val masks = LongArray(4) { random.nextLong() or 1L }
        val masked = LongArray(4) { index ->
            val offset = index * 8
            var chunk = 0L
            for (byte in 0 until 8) {
                chunk = chunk or ((key[offset + byte].toLong() and 0xFFL) shl (byte * 8))
            }
            chunk xor masks[index]
        }

        val kotlinDir = File(outDir, "kotlin/com/animo/app/provider").apply { mkdirs() }
        val maskedLiterals = masked.joinToString(",\n        ") { it.toString() + "L" }
        val maskLiterals = masks.joinToString(",\n        ") { it.toString() + "L" }
        val generated = buildString {
            appendLine("// GENERATED by :app:generateProviderVault - do not edit, do not commit.")
            appendLine("package com.animo.app.provider")
            appendLine()
            appendLine("internal object VaultMaterial {")
            appendLine("    private val masked = longArrayOf(")
            appendLine("        $maskedLiterals,")
            appendLine("    )")
            appendLine("    private val masks = longArrayOf(")
            appendLine("        $maskLiterals,")
            appendLine("    )")
            appendLine()
            appendLine("    /** Rebuilds the 32-byte AES key; no single literal is the key. */")
            appendLine("    fun keyBytes(): ByteArray {")
            appendLine("        val out = ByteArray(32)")
            appendLine("        for (index in 0 until 4) {")
            appendLine("            var chunk = masked[index] xor masks[index]")
            appendLine("            for (byte in 0 until 8) {")
            appendLine("                out[index * 8 + byte] = (chunk and 0xFFL).toByte()")
            appendLine("                chunk = chunk ushr 8")
            appendLine("            }")
            appendLine("        }")
            appendLine("        return out")
            appendLine("    }")
            appendLine("}")
        }
        File(kotlinDir, "VaultMaterial.kt").writeText(generated)
    }
}

